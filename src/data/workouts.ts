import type { Category, Difficulty, Workout, WorkoutBlock } from '../types'

/*
  THE PRE-MADE WORKOUTS — 70 ready-to-run sessions, 10 per skill.

  Each session is an ordered list of blocks. A block points at a drill by its `id`
  (see exercises.ts) and prescribes exactly how much of it to do.

  The `d()` helper writes one block. Everything is optional except the drill id:

      d('dr-cone-slalom', { sets: 6, secs: 25, rest: 20, after: 30 })
      d('sh-side-foot-placement', { sets: 3, reps: 20, est: 100, rest: 45 })

    sets   how many rounds                       (default 1)
    secs   seconds per set — TIMED drills only
    reps   reps per set — REP drills only
    est    how long one set of a rep drill takes. Rep drills are self-paced in the
           player; this is only so the length we advertise is honest.
    rest   seconds between sets      (leave it out to use the drill's own default)
    after  seconds of rest before the next drill
    note   a coaching note shown during that block

  A word on length: `estimatedMinutes` is the session as written in the programme.
  The app never shows it — every screen shows the length worked out from the blocks
  above, so what you see is what the session actually costs you.
*/

interface Prescription {
  sets?: number
  secs?: number
  reps?: number
  est?: number
  rest?: number
  after?: number
  note?: string
}

function d(exerciseId: string, p: Prescription = {}): WorkoutBlock {
  return {
    exerciseId,
    duration: p.secs ?? null,
    reps: p.reps ?? null,
    sets: p.sets ?? 1,
    restBetweenSets: p.rest ?? null,
    estimateSeconds: p.est ?? null,
    restAfter: p.after ?? 0,
    note: p.note ?? null,
  }
}

interface Draft {
  code: string
  name: string
  category: Category
  difficulty: Difficulty
  minutes: number
  focus: string
  goal: string
  description: string
  blocks: WorkoutBlock[]
}

function session(w: Draft): Workout {
  const slug = w.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
  return {
    id: `${w.code.toLowerCase()}-${slug}`,
    code: w.code,
    name: w.name,
    category: w.category,
    description: w.description,
    goal: w.goal,
    focus: w.focus,
    estimatedMinutes: w.minutes,
    difficulty: w.difficulty,
    isCustom: false,
    blocks: w.blocks,
  }
}

